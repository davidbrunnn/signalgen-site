/** The visitor's language: ?lang= first, then the cookie, then PT-BR. */
export function getLang(search?: { lang?: string } | null): Lang {
  if (search && isLang(search.lang)) return search.lang;
  try { const c = cookies().get('lang')?.value; if (isLang(c)) return c; } catch { /* outside a request */ }
  return 'pt';
}

